-- V004. Вместимость ячеек в литрах.
--
-- Что делает: ячейкам хранения со значением вместимости по умолчанию (1) ставит 1000 л.
-- Зачем: объём товара (product.volume) хранится в литрах (дм³), вместимость ячейки
-- (location.capacity) используется при автоматическом подборе ячейки в тех же единицах.
-- Прежнее значение по умолчанию 1 означало «не задано» и не позволило бы разместить ни один товар.
--
-- Идемпотентный: затрагивает только ячейки с capacity <= 1. Системные ячейки (1, 2) не меняются.

UPDATE location
SET capacity = 1000
WHERE capacity <= 1
  AND locationid NOT IN (1, 2);
